#!/usr/bin/env bash
# Prints the commands that publish hf-export/ to the public Hugging Face dataset.
# It uploads NOTHING itself: uploading is publishing (HF may cache/index it), so you run it.
#
#   bash tools/upload_embeddings_hf.sh [tag]      # default tag: v0.2
set -eu
cd "$(dirname "$0")/.."
TAG="${1:-v0.2}"
REPO="dekmATtud/consilia-embeddings"     # until v0.1 (23.10.2026): mschonhardt/consilia-embeddings
[ -f hf-export/bge-m3/chunks.f16.bin ] || { echo "run python src/export_embeddings_web.py first"; exit 1; }
REV=$(python3 -c "import json;print(json.load(open('site-data/manifest.json'))['revision'])")
cat > hf-export/README.md <<EOF
---
license: cc-by-4.0
---
# consilia-embeddings (work in progress)

**Work in progress. Data, translations and embeddings change without notice until v1.0.**

Chunk embeddings for the Consilia edition (Baldus de Ubaldis, *Consilia*, Venice 1575, five volumes; Panormitanus,
*Consilia*, Venice 1571), used by the search page of the portal https://dekm-tud.github.io/coding-consilia/ .
Models: \`bge-m3\` (BAAI/bge-m3), \`etp-bgem3-ft\` (mschonhardt/etp-bgem3-contrastive-ft), \`qwen3-0.6b\`
(Qwen/Qwen3-Embedding-0.6B), \`qwen3-4b\` (Qwen/Qwen3-Embedding-4B). Until v0.1 (23 October 2026) this dataset was
published as mschonhardt/consilia-embeddings.
Generated by \`src/export_embeddings_web.py\` from the edition data (site-data revision \`$REV\`).
Per model directory: \`chunks.f16.bin\` (raw little-endian float16, N x D, row-major) and \`chunks.json\`
(\`doc\` indexes into the edition's \`site-data/index.json\`; \`lang\` 0=Latin 1=English; \`kind\` 0=body 1=casus).
The frontend is pinned to a release tag (\`$TAG\`); rows are only valid for the matching data revision.
EOF
cat <<EOF
Review hf-export/README.md, then run:

  huggingface-cli login                                   # once
  huggingface-cli repo create consilia-embeddings --type dataset   # once, public
  huggingface-cli upload $REPO hf-export . --repo-type dataset --commit-message "$TAG (data revision $REV)"
  git -C /path/to/hf/clone tag $TAG                      # or create the tag in the HF web UI

Then move "https://huggingface.co/datasets/$REPO/resolve/$TAG/bge-m3/" to the FIRST position in
site-data/models.json, and (optionally) remove hf-export/ from PUBLISH in tools/build_pages_artifact.py.
EOF
