@mcp.tool()
def list_keywords(query: str = "", top_k: int = 50) -> list[dict]:
    """Browse or search the curated controlled vocabulary (3,463 terms) used to tag
    every consilium in the corpus.

    With no query, returns the top_k most frequent terms corpus-wide — a quick way
    to see what subject areas exist. With a query, returns every term whose label
    contains it (case-insensitive substring match), sorted by frequency — use this
    to check a term exists (and its exact spelling/casing) before calling
    consilia_by_keyword(), or to explore a subject area (e.g. query="marriage" surfaces
    every marriage-adjacent term, not just the exact word).

    Each result: {"label": the exact term (pass verbatim to consilia_by_keyword),
                  "doc_freq": number of consilia carrying this term}

    Args:
        query: Optional substring filter, e.g. "adultery" or "marr".
        top_k: Max terms to return (default 50, max 200).
    """
    top_k = min(max(1, top_k), 200)
    q = query.strip().lower()
    # doc_freq = consilia carrying the term in keywords_final, i.e. exactly what
    # consilia_by_keyword() returns (vocabulary.json's own doc_freq is pre-reduction)
    matches = [{"label": t["label"], "doc_freq": FINAL_FREQ.get(t["label"], 0)} for t in VOCABULARY
               if (q in t["label"].lower() if q else True) and FINAL_FREQ.get(t["label"], 0) > 0]
    matches.sort(key=lambda t: (-t["doc_freq"], t["label"]))
    return matches[:top_k]


@mcp.tool()
def consilia_by_keyword(
    keyword: str,
    top_k: int = 50,
    author_viaf: str | None = None,
    volume: str | None = None,
) -> list[dict]:
    """Return every consilium tagged with a given controlled-vocabulary term — the
    same aggregation the web frontend's search.html "Index" mode provides, for
    quickly clustering consilia by topic instead of by semantic similarity.

    Use list_keywords() first if you're not sure of a term's exact spelling — this
    matches the keyword exactly (case-sensitive), not by substring.

    Args:
        keyword: Exact vocabulary label, e.g. 'adultery', 'impotence', 'Trebellian portion'.
        top_k: Max consilia to return (default 50, max 200).
        author_viaf: Optional — filter by author directory name.
        volume: Optional — filter by print volume.
    """
    top_k = min(max(1, top_k), 200)
    ids = TERM_TO_IDS.get(keyword, [])
    if not ids:
        close = [t["label"] for t in VOCABULARY if keyword.lower() in t["label"].lower()][:8]
        return [{"error": f"No consilia tagged '{keyword}'.",
                 "did_you_mean": close}] if close else [{"error": f"'{keyword}' is not in the controlled vocabulary."}]

    results: list[dict] = []
    for cid in ids:
        c = CONSILIA.get(cid)
        if c is None:
            continue
        if author_viaf and c.get("author_viaf") != author_viaf:
            continue
        if volume and c.get("volume") != volume:
            continue
        results.append({
            "id":          cid,
            "n":           c.get("n"),
            "title":       c.get("title", ""),
            "volume":      c.get("volume", ""),
            "author_viaf": c.get("author_viaf", ""),
            "summary":     (c.get("summary") or "")[:400],
            "keywords":    c.get("keywords_final") or [],
        })
    results.sort(key=lambda r: (r["volume"], r["n"] or 0))
    return results[:top_k]



@mcp.tool()
def list_subjects(query: str = "", top_k: int = 60) -> list[dict]:
    """Browse the controlled subject scheme (Layer A): legal concepts in facets such as
    succession, marriage and dowry, persons, obligations, procedure, criminal law, statutes
    and public law. A language model assigned each consilium its central and secondary
    concepts. Prefer this over the free keywords for legal topics; then call
    consilia_by_subject() with the concept id.

    Args:
        query: Optional substring matched against the English, German and Latin labels and the id.
        top_k: Max concepts to return (default 60), most frequent first.
    """
    if not SUBJECTS:
        return [{"error": "subject layer not published (site-data/annotations/subjects.json missing)"}]
    cnt: dict[str, int] = {}
    cen: dict[str, int] = {}
    for d in SUBJECTS.get("docs", {}).values():
        for k in d.get("central", []):
            cnt[k] = cnt.get(k, 0) + 1
            cen[k] = cen.get(k, 0) + 1
        for k in d.get("secondary", []):
            cnt[k] = cnt.get(k, 0) + 1
    q = query.strip().lower()
    rows = []
    for c in SUBJECTS.get("concepts", []):
        if q and not any(q in (c.get(f) or "").lower() for f in ("en", "de", "la", "id")):
            continue
        rows.append({"id": c["id"], "label_en": c["en"], "label_de": c.get("de", ""), "label_la": c.get("la", ""),
                     "facet": SUBJ_FACETS.get(c["facet"], {}).get("en", c["facet"]), "scope": c.get("scope", ""),
                     "consilia": cnt.get(c["id"], 0), "central": cen.get(c["id"], 0)})
    rows.sort(key=lambda r: (-r["consilia"], r["label_en"]))
    return rows[:max(1, min(top_k, 200))]


@mcp.tool()
def consilia_by_subject(
    concept: str,
    central_only: bool = False,
    top_k: int = 50,
    author_viaf: str | None = None,
    volume: str | None = None,
) -> list[dict]:
    """Every consilium assigned to a subject concept (Layer A), central assignments first.

    Args:
        concept: Concept id from list_subjects(), e.g. 'succ_testament_form'.
        central_only: Only consilia where the concept is central.
        top_k: Max consilia (default 50, max 200).
        author_viaf: Optional author directory name filter.
        volume: Optional print volume filter.
    """
    if not SUBJECTS:
        return [{"error": "subject layer not published"}]
    if concept not in SUBJ_CONCEPTS:
        close = [c["id"] for c in SUBJECTS.get("concepts", []) if concept.lower() in (c["id"] + c["en"]).lower()][:8]
        return [{"error": f"'{concept}' is not a concept id.", "did_you_mean": close}]
    rows = []
    for cid, d in SUBJECTS.get("docs", {}).items():
        c = CONSILIA.get(cid)
        if c is None or (author_viaf and c.get("author_viaf") != author_viaf) or (volume and c.get("volume") != volume):
            continue
        if concept in d.get("central", []):
            rows.append((0, _brief(cid, c, assignment="central")))
        elif not central_only and concept in d.get("secondary", []):
            rows.append((1, _brief(cid, c, assignment="secondary")))
    rows.sort(key=lambda r: (r[0], r[1]["volume"], r[1]["n"] or 0))
    return [r for _, r in rows[:max(1, min(top_k, 200))]]


@mcp.tool()
def list_body_codes() -> dict:
    """The codebook of the layer "body and sexuality" (Layer B): codes such as adultery,
    impotence, pregnancy, virginity, wet-nursing, grouped (sexual offences, marriage as
    bodily union, reproduction, ...). Each occurrence has a role: topic or argument (the
    counted roles), case_fact, citation_only, formulaic. Returns the codes with the number
    of consilia carrying them (all roles, and counted roles only). Then call
    consilia_by_body_code().
    """
    if not BODY:
        return {"error": "body layer not published (site-data/annotations/intimate_body.json missing)"}
    counted = set(BODY.get("counted_roles_default", []))
    by: dict[str, dict] = {}
    for u in BODY.get("units", []):
        t = by.setdefault(u["code"], {"all": set(), "counted": set()})
        t["all"].add(u["doc"])
        if u["role"] in counted:
            t["counted"].add(u["doc"])
    codes = [{"id": c["id"], "label_en": c["label_en"], "label_de": c.get("label_de", ""), "label_la": c.get("label_la", ""),
              "group": c["group"], "consilia": len(by.get(c["id"], {"all": set()})["all"]),
              "consilia_counted": len(by.get(c["id"], {"counted": set()})["counted"])} for c in BODY.get("codes", [])]
    codes = [c for c in codes if c["consilia"]]
    codes.sort(key=lambda c: (-c["consilia_counted"], -c["consilia"]))
    return {"roles": BODY.get("roles"), "counted_roles_default": BODY.get("counted_roles_default"),
            "groups": BODY.get("groups"), "models": BODY.get("models"), "codes": codes,
            "note": BODY.get("note", "")}


@mcp.tool()
def consilia_by_body_code(
    code: str,
    roles: list[str] | None = None,
    top_k: int = 50,
    author_viaf: str | None = None,
    volume: str | None = None,
) -> list[dict]:
    """Every consilium carrying a Layer B code, with the Latin evidence quote and role of
    each occurrence. By default only the counted roles (topic, argument); pass roles to
    include case_fact, citation_only or formulaic occurrences.

    Args:
        code: Code id from list_body_codes(), e.g. 'adultery'.
        roles: Roles to include; default the counted roles.
        top_k: Max consilia (default 50, max 200).
        author_viaf: Optional author directory name filter.
        volume: Optional print volume filter.
    """
    if not BODY:
        return [{"error": "body layer not published"}]
    if code not in BODY_CODES:
        close = [c["id"] for c in BODY.get("codes", []) if code.lower() in (c["id"] + c["label_en"]).lower()][:8]
        return [{"error": f"'{code}' is not a code id.", "did_you_mean": close}]
    want = set(roles) if roles else set(BODY.get("counted_roles_default", []))
    by: dict[str, dict] = {}
    for u in BODY.get("units", []):
        if u["code"] != code or u["role"] not in want:
            continue
        c = CONSILIA.get(u["doc"])
        if c is None or (author_viaf and c.get("author_viaf") != author_viaf) or (volume and c.get("volume") != volume):
            continue
        r = by.setdefault(u["doc"], _brief(u["doc"], c, occurrences=[]))
        r["occurrences"].append({"role": u["role"], "evidence_la": u.get("evidence_la", ""), "status": u.get("status"), "section": u.get("section")})
    rows = sorted(by.values(), key=lambda r: (-len(r["occurrences"]), r["volume"], r["n"] or 0))
    return rows[:max(1, min(top_k, 200))]


@mcp.tool()
def list_references(query: str = "", top_k: int = 60) -> list[dict]:
    """Cited works (Layer C): titles of the Corpus iuris civilis (D. = Digest, C. = Codex, Inst.,
    Nov./Auth.), the Corpus iuris canonici (X = Liber Extra, VI = Sextus, Clem., Decr.) and the
    Libri feudorum (LF) that the consilia cite, resolved by rule from the printed abbreviations
    ("ff. de pac. l. tale pactum" -> "D. 2.14", Digest, De pactis). About half of all citation
    spans resolve; the others are kept as printed only. Each entry: key, title, number of consilia
    and passages, printed forms. Then call consilia_by_reference(key).

    Args:
        query: Optional substring matched against the key, the title or the printed forms.
        top_k: Max entries (default 60), most cited first.
    """
    if not REFS or not REFS.get("refs"):
        return [{"error": "citation layer not published or works not resolved"}]
    q = query.strip().lower()
    rows = [{"key": k, "title": v.get("title", ""), "consilia": len(v["docs"]), "passages": v["n"], "printed_forms": v["forms"]}
            for k, v in REFS["refs"].items() if not q or q in k.lower() or q in (v.get("title") or "").lower() or any(q in f.lower() for f in v["forms"])]
    rows.sort(key=lambda r: -r["consilia"])
    return rows[:max(1, min(top_k, 300))]


