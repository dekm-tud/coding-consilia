# ---------------------------------------------------------------------------
# Embedding backend — lazy-loaded, one GPU-resident model at a time
# ---------------------------------------------------------------------------

_LOADED_TAG: str | None = None
_LOADED_MODEL = None


def _get_embedder(tag: str):
    """Return a query-embedding function for *tag*, (re)loading the underlying
    model onto the GPU only if a different tag is currently loaded."""
    global _LOADED_TAG, _LOADED_MODEL
    if tag != _LOADED_TAG:
        from sentence_transformers import SentenceTransformer
        if _LOADED_MODEL is not None:
            log.info("Unloading %s to switch to tag %r …", _LOADED_TAG, tag)
            del _LOADED_MODEL
            gc.collect()
            torch.cuda.empty_cache()
        cfg = MODEL_REGISTRY[tag]
        log.info("Loading %s locally for query embedding (tag=%r) …", cfg["id"], tag)
        device = "cuda" if torch.cuda.is_available() else "cpu"
        if device == "cuda":
            free_b, _total = torch.cuda.mem_get_info()
            need_b = {"qwen3-4b": 9.5e9, "qwen8b_en": 17e9, "qwen4b_en": 9.5e9}.get(tag, 3e9)
            if free_b < need_b:
                log.warning("GPU has %.1f GB free, %s needs about %.1f GB: embedding queries on the CPU (slower).", free_b / 1e9, tag, need_b / 1e9)
                device = "cpu"
        kwargs = dict(cfg["model_kwargs"])
        if device == "cpu" and "dtype" in kwargs:
            kwargs["dtype"] = torch.bfloat16
        elif device == "cpu" and cfg.get("web") and "4b" in tag.lower():
            kwargs["dtype"] = torch.bfloat16              # 4B in float32 would need 16 GB of RAM
        model = SentenceTransformer(cfg["id"], model_kwargs=kwargs, device=device)
        if cfg["max_seq_length"]:
            model.max_seq_length = cfg["max_seq_length"]
        _LOADED_MODEL = model
        _LOADED_TAG = tag
        log.info("Model ready.")

    cfg = MODEL_REGISTRY[tag]
    model = _LOADED_MODEL

    def _embed(text: str) -> np.ndarray:
        kwargs = {"normalize_embeddings": True}
        if cfg["prompt_query"]:
            kwargs["prompt_name"] = cfg["prompt_query"]
        return model.encode([(cfg.get("query_prefix") or "") + text], **kwargs)[0].astype(np.float32)

    return _embed


log.info("Ready — %d consilia, embeddings available for: %s.", len(CONSILIA), sorted(EMBED_DATA) or "none")

