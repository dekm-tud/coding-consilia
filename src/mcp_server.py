"""
MCP server for the Consilia corpus.

Exposes these tools to Claude Desktop and Claude Code:
  corpus_stats()                                     — total consilia, per-author/per-volume
                                                        breakdown, vocabulary size — the
                                                        only source of a real corpus-wide count
  search_consilia(query, model, top_k, author_viaf, volume) — semantic search,
                                                        chunked + max-pooled (see below)
  list_embedding_models()                            — which embedding models are
                                                        available for search_consilia's
                                                        `model` argument
  get_consilium(consilium_id)                        — return full text of a consilium
  list_keywords(query, top_k)                        — browse/search the controlled
                                                        vocabulary (output/vocabulary.json)
  consilia_by_keyword(keyword, top_k, author_viaf, volume) — every consilium tagged
                                                        with a given vocabulary term —
                                                        the keyword-index aggregation
                                                        also exposed in search.html's
                                                        "Index" mode
  list_subjects(query, top_k)                        — the controlled subject scheme
                                                        (Layer A, per consilium, central/
                                                        secondary), with counts
  consilia_by_subject(concept, central_only, top_k, author_viaf, volume)
  list_body_codes()                                  — the codebook "body and sexuality"
                                                        (Layer B, per text unit, with roles)
  consilia_by_body_code(code, roles, top_k, author_viaf, volume) — with the Latin evidence quotes
  list_references(query, top_k) / consilia_by_reference(key, …)   — Layer C: cited works, resolved by rule
  list_jurists(query, top_k) / consilia_by_jurist(name, …)        — Layer C: jurists cited by name

Layers A and B are machine annotations (site-data/annotations/*.json, written by
src/annotate/export.py); get_consilium() returns a consilium's assignments too.

Embeddings: generated by src/gpu/embed_consilia_chunked.py (run on a GPU server,
then copy the output back) — one row per body-section chunk, not one per
consilium, so a document's score is the max over its own chunk rows. This is
a *different* file from the one assets/search-app.js uses (that one is the
frontend's own BGE-M3 chunked embeddings, produced locally by
src/embed_consilia.py) — the two are independent so each can pick its own
model without touching the other.

All three candidates in MODEL_REGISTRY below can be selected per call via
search_consilia(..., model="qwen8b_en"|"qwen4b_en"|"canonberta_lat") — whichever
of output/embeddings_{tag}.safetensors / _meta.json exist are loaded (cheaply,
as plain arrays) at startup. The actual GPU-resident embedding model is loaded
lazily on first use of a given tag and cached; switching to a different tag
unloads the previous one first, since only one needs to be GPU-resident at a
time. CONSILIA_EMBED_TAG picks the default when a call doesn't specify `model`.

Claude Desktop / Claude Code config:
  {
    "command": "/path/to/Consilia/.venv/bin/python",
    "args":    ["/path/to/Consilia/src/mcp_server.py"],
    "cwd":     "/path/to/Consilia",
    "env": {
      "CONSILIA_EMBED_TAG": "qwen4b_en"   (optional — "qwen8b_en" or "canonberta_lat")
    }
  }
"""

