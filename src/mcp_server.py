def _citations_of(cid: str) -> list[dict]:
    """cited works and jurists of one consilium from its print's shard (loaded on first use)"""
    c = CONSILIA.get(cid)
    if not c or not REFS:
        return []
    vol = c.get("volume", "")
    if vol not in _REF_SHARDS:
        _p = _SITE / "annotations" / "references" / f"{vol}.json"
        _REF_SHARDS[vol] = json.loads(_p.read_text(encoding="utf-8")) if _p.exists() else {}
    groups = {"CIT_CIV": "civil", "CIT_CAN": "canon", "CIT_FEUD": "feudal", "CIT_OTHER": "other"}
    out = [{"corpus": groups[sp["l"]], "as_printed": sp["t"], "resolved": sp.get("rk"), "status": sp.get("st")} for sp in _REF_SHARDS[vol].get(cid, []) if sp["l"] in groups]
    cnt: dict[str, dict] = {}
    for sp in _REF_SHARDS[vol].get(cid, []):
        if sp.get("jk"):
            e = cnt.setdefault(sp["jk"], {"jurist": sp["jk"], "n": 0, "as_printed": sp["t"]}); e["n"] += 1
    return out + sorted(cnt.values(), key=lambda e: -e["n"])


